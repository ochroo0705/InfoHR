"""Help entries for the employee area: finding a person, hiring, importing, and the basic changes on one person
(inventory rows 1-19 except the personal tab rows 20-21 of docs/assistant-coverage-inventory.md).

Person-bound entries (`person_tab` set) open that person's employee page; the steps go on from there. `need` is the
view's own check: `access.can_manage` (macs.manage_employees) for job changes, `can_manage_salary` plus
`can_view_salary` for the salary entries, `macs.view_employees` for the list.
"""

from datetime import date

from accounts.models import User
from employees import access

from assistant.entry import HelpEntry


def _sees_list(user: User, day: date) -> bool:
    return user.has_perm("macs.view_employees")


def _manages(user: User, day: date) -> bool:
    return access.can_manage(user)


def _salary_rights(user: User, day: date) -> bool:
    """The salary screens' check: view_salary and manage_salary together (the Accountant role has both)."""
    return access.can_view_salary(user) and access.can_manage_salary(user)


def _personal_rights(user: User, day: date) -> bool:
    """The personal tab's edit check: manage_employees and view_personal (HR and Admin have both)."""
    return access.can_manage(user) and user.has_perm("macs.view_personal")



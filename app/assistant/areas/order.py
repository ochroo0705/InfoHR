"""Help entries for the HR orders register «Тушаалын бүртгэл» (inventory rows 25-31 of
docs/assistant-coverage-inventory.md).

The register is not person-bound: its entries open `employees:orders`, and the steps go on from a row, which opens the
order's pop-up. Viewing needs `macs.view_employees` (the register's own check, as the Ctrl+K palette). Editing, the
signed scan and the Word/PDF draft need `access.can_manage` (macs.manage_employees), as the views do. Cancelling a hire
order also needs the hire-order switch on (CompanySettings, order_hired), because without it no hire order exists.
"""

from datetime import date

from accounts.models import User
from employees import access
from employees.models import OrderType
from employees.services import orders

from assistant.entry import HelpEntry


def _sees_register(user: User, day: date) -> bool:
    return user.has_perm("macs.view_employees")


def _manages(user: User, day: date) -> bool:
    return access.can_manage(user)


def _cancels_hire_order(user: User, day: date) -> bool:
    """The pop-up's «Тушаал цуцлах» check: manage rights, and the install keeps hire orders on."""
    return access.can_manage(user) and orders.requires_order(OrderType.HIRED.value)



def expected(case: EvalCase, role: str) -> str:
    """The entry key this case should get for this role: the intent if allowed, else the fallback, else ""."""
    if case.intent in ROLE_ENTRIES[role]:
        return case.intent
    return FALLBACK.get(case.intent, {}).get(role, "")


@dataclass(frozen=True)
class TableCase:
    """A sentence that should become staff-table filters. `expected` is the filter query the settled filters must
    equal (order-insensitive, see evalcheck.same_filters). A lookup value is written by its exact name as
    `param~Name`; the eval turns it into the row's id at run time. `{month_start}` and `{month_end}` are this month's
    first and last day, so the case stays right on any day."""

    question: str
    expected: str
    ask: str = ""  # the lookup the answer must ask about (a phrase with several rows); "" = no ask expected
    unapplied: bool = False  # the answer must name at least one part it could not use
    gated: bool = True  # False: reported but not counted in the 90% gate (unconfirmed code or a stage 2 feature)
    roles: tuple[str, ...] = ()  # the roles this case runs for; () = every role that may open the staff table
    none_ok: bool = False  # True: a "none" answer (no table asked) passes, as a case that expects no filter at all
    previous: str = ""  # the address query of the earlier answer the question follows (a follow-up); "" = none
    chart: str = (
        ""  # "" = no chart checked; "kind:by" = the plan asks for a chart of that kind, grouped by `by` ("" none)
    )


